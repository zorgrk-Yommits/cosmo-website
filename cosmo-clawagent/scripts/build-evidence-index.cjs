#!/usr/bin/env node
// Writes a plain index.html into public folders that would otherwise be served
// as a bare directory listing (`serve` lists a folder that has no index.html).
//
// Only folders named in FOLDERS are touched, and only when they have no
// index.html or one that this script wrote earlier (see MARKER). Hand-made
// pages are never overwritten. The generated page is a file list, not part of
// any evidence bundle: the bundle's own index.txt stays the reference for
// fingerprints.
//
//   node scripts/build-evidence-index.cjs      (also runs as `prebuild`)

const fs = require('node:fs');
const path = require('node:path');

const PUBLIC = path.resolve(__dirname, '..', 'public');
const MARKER = '<!-- generated by scripts/build-evidence-index.cjs -->';

const FOLDERS = {
  evidence: {
    title: 'Evidence files',
    lead: 'The published files behind the proofs on this site. Each folder belongs to one job or run.',
  },
  'evidence/pilot-001': {
    title: 'PILOT-001: first job paid on the market',
    lead: 'The fixed job description and the delivered result of the first job that ran from posting to payment on Supra Mainnet (2026-07-17).',
  },
  'evidence/patch-001': {
    title: 'PATCH-001: a software fix, checked automatically',
    lead: 'The request, the delivered patch and the signed delivery of a job that was paid after an automatic ten-point check (2026-07-10).',
  },
  'evidence/attest-001': {
    title: 'ATTEST-001: a signed report, checked automatically',
    lead: 'The request and the signed delivery of a job that was paid after an automatic check (2026-07-08).',
  },
  'evidence/buyer-proof-001': {
    title: 'Buyer proof 001',
    lead: 'The fixed job description, the delivered patch and the comparison result of one market job.',
  },
  'evidence/mcp-probe-002': {
    title: 'MCP-PROBE-002: a behaviour test',
    lead: 'The evidence file and the full transcript of a behaviour test of a public MCP server.',
  },
  'evidence/vlm-001': {
    title: 'VLM-001: liquidity under rules, a full run',
    lead: 'The rules file, the evidence for each action (open, reset, close), the end of the permission and the verdicts of the checking programs. Ethereum mainnet, 2026-08-22 to 2026-09-05.',
    more: [['Proof page', '/mandates/vlm-001/'], ['The checking program', '/verifier/']],
  },
  vsa: {
    title: 'VenueSettlementAttestation v1',
    lead: 'A specification for trading venues: how a venue can state, in a signed file, how a trade ended. The text is in index.txt.',
  },
  media: {
    title: 'Media',
    lead: 'Video files of the project.',
  },
};

// Titles for folders that have a hand-made page of their own.
const NOTES = {
  'evidence/execution-case-001': 'Case 001: a trade under fixed rules',
  'evidence/execution-case-002': 'Case 002: a work delivery under fixed rules',
  'evidence/execution-case-002g': 'Case 002-G: delivery and approval under fixed rules',
};

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

function size(n) {
  if (n < 1024) return `${n} B`;
  if (n < 1024 * 1024) return `${(n / 1024).toFixed(1)} kB`;
  return `${(n / 1024 / 1024).toFixed(1)} MB`;
}

function page(rel, meta, entries) {
  const up = rel.includes('/') ? '../' : '/assurance/';
  const upLabel = rel.includes('/') ? 'All evidence folders' : 'Proof overview';
  const rows = entries
    .map((e) => {
      const note = e.dir ? (FOLDERS[`${rel}/${e.name}`]?.title ?? NOTES[`${rel}/${e.name}`] ?? 'folder') : size(e.size);
      const href = e.dir ? `${encodeURIComponent(e.name)}/` : encodeURIComponent(e.name);
      return `    <li><a href="${href}">${esc(e.name)}${e.dir ? '/' : ''}</a><span>${esc(note)}</span></li>`;
    })
    .join('\n');
  const more = (meta.more ?? []).map(([l, h]) => `<a href="${h}">${esc(l)}</a>`).join(' · ');
  const hasTxt = entries.some((e) => e.name === 'index.txt');
  return `<!doctype html>
${MARKER}
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(meta.title)} | COSMO</title>
<style>
  :root { color-scheme: dark; }
  body { margin: 0; background: #08090B; color: #A7B0BC; font: 16px/1.6 ui-sans-serif, system-ui, -apple-system, "Segoe UI", sans-serif; }
  main { max-width: 44rem; margin: 0 auto; padding: 3rem 1rem 4rem; }
  a { color: #4FD3D9; }
  .top { font: 12px/1.4 ui-monospace, SFMono-Regular, Menlo, monospace; letter-spacing: .08em; text-transform: uppercase; }
  .top a { color: #757E8C; text-decoration: none; }
  h1 { color: #F2F4F7; font-size: 1.75rem; line-height: 1.2; margin: 1.25rem 0 .75rem; text-wrap: balance; }
  ul { list-style: none; margin: 1.5rem 0 0; padding: 0; border: 1px solid rgba(255,255,255,.10); border-radius: 12px; overflow: hidden; }
  li { display: flex; flex-wrap: wrap; justify-content: space-between; gap: .25rem 1rem; padding: .7rem 1rem; border-top: 1px solid rgba(255,255,255,.06); font: 14px/1.5 ui-monospace, SFMono-Regular, Menlo, monospace; }
  li:first-child { border-top: 0; }
  li a { overflow-wrap: anywhere; }
  li span { color: #757E8C; }
  .note { color: #757E8C; font-size: 14px; margin-top: 1.5rem; }
</style>
</head>
<body>
<main>
  <div class="top"><a href="/">COSMO</a> · <a href="${up}">${esc(upLabel)}</a></div>
  <h1>${esc(meta.title)}</h1>
  <p>${esc(meta.lead)}</p>
  ${more ? `<p>${more}</p>` : ''}
  <ul>
${rows}
  </ul>
  <p class="note">${hasTxt ? 'index.txt lists the files of this folder with their SHA3-256 fingerprints. ' : ''}This page is a generated file list. It is not part of the evidence itself.</p>
</main>
</body>
</html>
`;
}

let written = 0;
for (const [rel, meta] of Object.entries(FOLDERS)) {
  const dir = path.join(PUBLIC, rel);
  if (!fs.existsSync(dir)) continue;
  const target = path.join(dir, 'index.html');
  if (fs.existsSync(target) && !fs.readFileSync(target, 'utf8').includes(MARKER)) continue; // hand-made page
  const entries = fs
    .readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.name !== 'index.html' && !e.name.startsWith('.'))
    .map((e) => ({ name: e.name, dir: e.isDirectory(), size: e.isDirectory() ? 0 : fs.statSync(path.join(dir, e.name)).size }))
    .sort((a, b) => Number(b.dir) - Number(a.dir) || a.name.localeCompare(b.name));
  const html = page(rel, meta, entries);
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== html) {
    fs.writeFileSync(target, html);
    written += 1;
  }
}
console.log(`evidence-index: ${written} page(s) written`);
